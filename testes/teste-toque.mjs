import { createRequire } from 'module'; const req = createRequire(import.meta.url); const { chromium, devices } = req('playwright');
const b = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const ctx = await b.newContext({ ...devices['Galaxy Tab S4 landscape'] });
const p = await ctx.newPage();
const erros = []; p.on('pageerror', (e) => erros.push(e.message));
await p.goto((process.env.URL || 'http://localhost:8788') + '/#teste');
await p.evaluate(() => localStorage.clear());
await p.tap('#bt-sozinho');
// sem mundo salvo, "Jogar sem conta" abre primeiro a tela de criar mundo
if (await p.isVisible('#m-novo')) await p.tap('#m-novo button[type=submit]');
await p.waitForFunction(() => window.__jogo && window.__jogo.jog, null, { timeout: 20000 });
await p.waitForTimeout(1500);
await p.evaluate(() => { window.__jogo.jog.pitch = -0.5; });
await p.waitForTimeout(300);
const vp = p.viewportSize();
const antes = await p.evaluate(() => window.__jogo.mundo.listarEdicoes().length);
await p.touchscreen.tap(vp.width * 0.7, vp.height * 0.5);
await p.waitForTimeout(400);
const depois = await p.evaluate(() => window.__jogo.mundo.listarEdicoes().length);
// joystick: simula toque arrastando no lado esquerdo
const cdp = await ctx.newCDPSession(p);
const x0 = vp.width * 0.2, y0 = vp.height * 0.6;
const pos0 = await p.evaluate(() => ({ ...window.__jogo.jog.pos }));
await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: x0, y: y0, id: 1 }] });
await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: x0, y: y0 - 60, id: 1 }] });
await p.waitForTimeout(1500);
await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
const pos1 = await p.evaluate(() => ({ ...window.__jogo.jog.pos }));
console.log('blocos colocados com toque:', depois - antes, '| andou:', Math.hypot(pos1.x - pos0.x, pos1.z - pos0.z).toFixed(2));
await p.screenshot({ path: (process.env.SAIDA || '/tmp') + '/tablet.png' });
console.log(erros.join('\n') || 'sem erros');
await b.close();
